'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require(process.argv[2]||'playwright');
const out=path.resolve(__dirname,'../test-results');fs.mkdirSync(out,{recursive:true});
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'msedge'});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:720}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto('http://127.0.0.1:4173/index.html');
    await page.locator('[data-action="play-immediately"]').click();
    assert.equal(await page.evaluate(()=>FrontlinesApp.getSettings().aiDifficulty),'easy');
    await page.evaluate(()=>FrontlinesShell.openSettings('learning'));
    assert.equal(await page.locator('#shell-difficulty').inputValue(),'easy');
    await page.locator('[data-pref="tutorialHints"]').uncheck();
    assert.equal(await page.evaluate(()=>FrontlinesApp.getSettings().aiDifficulty),'easy','Changing hints must preserve the onboarding difficulty');
    await page.keyboard.press('Escape');
    await page.evaluate(()=>{FrontlinesApp.startTutorial(false);FrontlinesApp.dispatch({type:'endTurn'});});
    assert.equal(await page.locator('#toast.visible.error').count(),1);
    await page.evaluate(()=>FrontlinesApp.tutorial.next());
    assert.equal(await page.locator('#toast.visible').count(),0,'Loading the next lesson clears the previous error toast');
    assert.equal(await page.locator('#toast').innerText(),'');
    await page.evaluate(()=>FrontlinesApp.tutorial.exit('skip'));
    assert.equal(await page.evaluate(()=>FrontlinesShell.getState().preferences.aiDifficulty),'easy');
    await page.evaluate(()=>{
      FrontlinesApp.startTutorial(false);
      FrontlinesApp.startMatch({mode:'ai',aiDifficulty:'expert',seed:67081});
      const original=FrontlinesAI.explainAction;window.reviewDecisions=[];
      FrontlinesAI.explainAction=(state,options)=>{window.reviewDecisions.push(options.difficulty);return original(state,options);};
      FrontlinesShell.openSettings('learning');
    });
    assert.equal(await page.locator('#shell-difficulty').inputValue(),'expert');
    await page.locator('#shell-difficulty').selectOption('easy');
    await page.locator('#shell-ai-speed').selectOption('fast');
    await page.keyboard.press('Escape');
    await page.locator('[data-action="end-turn"]').click();
    assert.match(await page.locator('.order-guidance small').innerText(),/AI difficulty: expert/);
    await page.waitForSelector('.ai-activity small');
    await page.evaluate(()=>FrontlinesShell.openSettings('learning'));
    assert.ok(await page.evaluate(()=>window.reviewDecisions.length>0&&window.reviewDecisions.every(d=>d==='expert')),'An active match must keep its selected difficulty');
    assert.equal(await page.locator('.ai-activity small').count(),1);
    await page.locator('[data-pref="actionExplanations"]').uncheck();
    assert.equal(await page.locator('.ai-activity small').count(),0,'Existing explanation hides immediately');
    assert.equal(await page.locator('.ai-activity b').count(),1,'Action notification remains readable');
    await page.locator('[data-pref="actionExplanations"]').check();
    assert.equal(await page.locator('.ai-activity small').count(),1);
    await page.locator('[data-pref="tutorialHints"]').check();
    await page.locator('[data-shell-action="reset-hints"]').click();
    await page.keyboard.press('Escape');
    await page.evaluate(()=>FrontlinesApp.startMatch({mode:'hotseat',developer:true,bothHands:true,seed:67082}));
    const deploy=await page.evaluate(()=>{
      const state=FrontlinesApp.getState();
      return FrontlinesEngine.legalActions(state).find(a=>a.type==='deploy'&&FrontlinesData.CARDS[state.players[0].hand.find(c=>c.uid===a.handUid).cardId].traits.length&&FrontlinesEngine.actionCost(state,a).commandActions===0);
    });
    assert.ok(deploy);
    await page.locator('[data-action="hand"][data-uid="'+deploy.handUid+'"]').click();
    assert.match(await page.locator('.cost-preview').innerText(),/Deployment cost:.*0 Command Actions/);
    assert.equal(await page.locator('.context-tip').count(),1);
    await page.locator('.territory[data-territory="'+deploy.territory+'"] .territory-header').click();
    await page.locator('.unit[data-uid="'+deploy.handUid+'"]').click();
    const preview=await page.locator('.cost-preview').innerText();
    assert.match(preview,/Committed Presence: \d+ \(already deployed\)/);
    assert.match(preview,/Move \/ attack: 0 Capacity · 1 Command Action/);
    await page.evaluate(()=>FrontlinesShell.openSettings('learning'));
    await page.locator('[data-shell-action="reset-hints"]').click();
    assert.equal(await page.locator('.context-tip').count(),0,'Reset tips removes the existing tip immediately');
    await page.keyboard.press('Escape');assert.equal(await page.locator('.context-tip').count(),0);
    assert.deepEqual(errors,[]);
    const result={passed:true,onboardingAndTutorialDifficultySync:true,explicitMatchDifficultySync:true,activeMatchDifficultyFixed:true,pausedTutorialDoesNotRelabelNormalMatch:true,explanationToggleImmediate:true,tipResetImmediate:true,settingsCloseRestoresCommands:true,newLessonClearsStaleToast:true,deploymentAndCommandCostsDistinct:true,aiDecisionFixture:true,errors};
    fs.writeFileSync(path.join(out,'browser-preferences-sprint6.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
