'use strict';
// Optional browser regression checks; use an existing Playwright installation.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.argv[2]||'playwright');
const base=path.resolve(__dirname,'..'),out=path.join(base,'test-results');
fs.mkdirSync(out,{recursive:true});
const waitFinished=page=>page.waitForFunction(()=>['completed','stopped','error'].includes(FrontlinesSimulatorApp.getStatus().status),{},{timeout:90000});

(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1366,height:768},acceptDownloads:true});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  await page.goto('http://127.0.0.1:4173/simulator.html');
  await page.evaluate(()=>{localStorage.clear();});
  await page.reload();
  assert.equal(await page.locator('#balance-profile option').count()>=3,true);
  assert.equal(await page.locator('#ai-a option').count(),3);
  assert.equal(await page.locator('[data-count="50000"]').count(),1);
  await page.locator('#balance-profile').selectOption('candidate');
  await page.locator('#ai-a').selectOption('faction');
  await page.locator('#ai-b').selectOption('baseline');
  await page.locator('#match-count').fill('20');
  await page.locator('#seed').fill('1209');
  await page.locator('#run-button').click();
  await waitFinished(page);
  const initial=await page.evaluate(()=>FrontlinesSimulatorApp.getReport());
  assert.equal(initial.completed,20);
  assert.equal(initial.options.balanceProfile,'candidate');
  assert.deepEqual(initial.options.aiProfiles,['faction','baseline']);
  assert.equal(initial.summary.errors,0);
  assert.equal(initial.execution.runner,'worker');
  assert.ok(initial.summary.diagnostics.economyByFaction.length);
  assert.ok(initial.summary.turns.p95>=initial.summary.turns.median);
  await page.locator('[data-tab="diagnostics"]').click();
  assert.ok((await page.locator('#length-metrics').innerText()).includes('95th percentile'));
  await page.locator('#view-diagnostics details').nth(1).locator('summary').click();
  assert.ok((await page.locator('#economy-table').innerText()).includes('Bruiser'));
  await page.locator('[data-tab="cards"]').click();
  await page.locator('#card-metric-sort').selectOption('damageDealt');
  assert.equal(await page.locator('#card-rows tr').count(),24);
  await page.locator('#card-faction-filter').selectOption('stonewall');
  assert.equal(await page.locator('#card-rows tr').count(),12);
  await page.locator('[data-tab="matches"]').click();
  await page.locator('#match-rows [data-match="0"]').click();
  await page.waitForFunction(()=>document.querySelector('#replay-trace').textContent.includes('Presence before:'));
  const trace=await page.locator('#replay-trace').innerText();
  assert.ok(trace.includes('Reason:'));
  assert.ok(trace.includes('score'));
  assert.ok(trace.includes('Industrial District')||trace.includes('Freight Yards'));
  assert.equal(await page.locator('#territory-chart').isVisible(),true);
  await page.locator('#chart-turn-slider').evaluate(input=>{input.value='1';input.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.ok((await page.locator('#trace-search').inputValue()).startsWith('Turn '));
  await page.locator('#rerun-replay').click();
  await waitFinished(page);
  const repeated=await page.evaluate(()=>FrontlinesSimulatorApp.getReport());
  assert.equal(repeated.completed,1);
  assert.equal(repeated.matches[0].seed,initial.matches[0].seed);
  assert.equal(repeated.matches[0].winner,initial.matches[0].winner);
  assert.equal(repeated.matches[0].decisions,initial.matches[0].decisions);
  const oldPath=path.join(out,'sprint3-previous.json');
  fs.writeFileSync(oldPath,JSON.stringify(initial));
  await page.locator('[data-tab="compare"]').click();
  await page.locator('#import-report').setInputFiles(oldPath);
  await page.waitForFunction(()=>document.querySelector('#comparison-notice').textContent.includes('sample')||document.querySelector('#comparison-notice').textContent.includes('Paired seeds'));
  assert.equal(await page.locator('#comparison-rows tr').count(),5);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export-html').click();
  const htmlDownload=await downloadPromise,htmlPath=path.join(out,'sprint3-lab-report.html');
  await htmlDownload.saveAs(htmlPath);
  assert.ok(fs.readFileSync(htmlPath,'utf8').includes('Frontlines'));
  await page.reload();
  assert.equal(await page.locator('#balance-profile').inputValue(),'candidate');
  assert.equal(await page.locator('#ai-a').inputValue(),'faction');
  for(const width of [1366,1024,390]){
    await page.setViewportSize({width,height:768});
    const dimensions=await page.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
    assert.ok(dimensions.scroll<=dimensions.width+1,`Lab overflow at ${width}: ${JSON.stringify(dimensions)}`);
  }
  await page.setViewportSize({width:1366,height:768});
  await page.goto(pathToFileURL(path.join(base,'simulator.html')).href);
  await page.evaluate(()=>{localStorage.clear();});await page.reload();
  await page.locator('#match-count').fill('1000');
  await page.locator('#run-button').click();
  await page.waitForFunction(()=>FrontlinesSimulatorApp.getStatus().status==='running');
  await page.locator('#pause-button').click();
  await page.waitForTimeout(100);
  const paused=await page.evaluate(()=>FrontlinesSimulatorApp.getStatus());
  await page.waitForTimeout(200);
  assert.deepEqual((await page.evaluate(()=>FrontlinesSimulatorApp.getStatus())).completed,paused.completed);
  assert.equal(paused.runner,'cooperative');
  await page.locator('#stop-button').click();await waitFinished(page);
  assert.equal((await page.evaluate(()=>FrontlinesSimulatorApp.getStatus())).status,'stopped');
  const partial=await page.evaluate(()=>FrontlinesSimulatorApp.getReport());
  assert.equal(partial.completed,partial.matches.length);
  assert.equal(partial.execution.status,'stopped');

  await page.goto(pathToFileURL(path.join(base,'index.html')).href);
  await page.evaluate(()=>{localStorage.clear();});await page.reload();
  const liveStart=await page.evaluate(()=>{
    FrontlinesApp.startMatch({factions:['nightwalker','rogue'],seed:6411,mode:'hotseat',config:{...FrontlinesData.DEFAULT_CONFIG}});
    return {privacy:FrontlinesApp.getUIState().privacy,hands:document.querySelectorAll('.hand-area .hand-card').length,report:FrontlinesApp.getPlaytestReport(),runtime:FrontlinesRuntime};
  });
  assert.equal(liveStart.privacy,true);assert.equal(liveStart.hands,0);assert.equal(liveStart.report,null);
  assert.equal(liveStart.runtime.aiProfile,'faction');
  const played=await page.evaluate(()=>{
    let count=0,handoffs=0;
    while(FrontlinesApp.getState().winner===null&&count<10000){
      if(FrontlinesApp.getUIState().privacy){if(document.querySelectorAll('.hand-area .hand-card').length)throw new Error('Hand visible during privacy');document.querySelector('[data-action="reveal"]').click();handoffs++;}
      const state=FrontlinesApp.getState(),decision=FrontlinesAI.explainAction(state),action=decision.action;
      const result=FrontlinesApp.dispatch(action,decision);if(!result.ok)throw new Error(result.error);count++;
    }
    return {count,handoffs,state:FrontlinesApp.getState(),report:FrontlinesApp.getPlaytestReport(),recent:FrontlinesApp.getRecentMatches()};
  });
  assert.ok(played.state.winner!==null,'Live match did not finish');
  assert.ok(played.handoffs>5);assert.equal(played.report.telemetry.decisions,played.count);
  assert.equal(played.report.telemetry.winner,played.state.winner);
  assert.ok(played.report.telemetry.trace.length>0);
  assert.equal(played.recent.length,1);
  assert.equal('trace' in played.recent[0],false);
  await page.waitForSelector('[data-action="playtest-report"]');
  await page.locator('[data-action="playtest-report"]').last().click();
  await page.locator('#feedback-confusing').fill('Test feedback: response timing was unclear.');
  await page.locator('#feedback-inevitable').fill('4');
  const playtestDownload=page.waitForEvent('download');
  await page.locator('[data-action="download-playtest"][data-format="json"]').click();
  const downloaded=await playtestDownload,playtestPath=path.join(out,'sprint3-live-playtest.json');await downloaded.saveAs(playtestPath);
  const playtest=JSON.parse(fs.readFileSync(playtestPath,'utf8'));
  assert.equal(playtest.feedback.inevitableTurn,4);
  assert.ok(playtest.feedback.confusing.includes('response timing'));
  assert.equal(playtest.match.nonCompetitive,false);
  assert.equal(playtest.match.seed,6411);
  await page.locator('[data-action="close-modal"]').last().click();
  await page.locator('[data-action="new-match"]').click();
  await page.locator('[data-action="recent-matches"]').click();
  assert.ok((await page.locator('.recent-table').innerText()).includes('6411'));
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({workerCompleted:initial.completed,richTrace:true,territoryChart:true,exactReplay:true,comparison:true,htmlExport:true,fileStopCompleted:partial.completed,liveDecisions:played.count,privacyHandoffs:played.handoffs,playtestFeedback:true,consoleErrors:errors.length},null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
